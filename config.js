/* Адрес API.
 *
 * Три случая, и все три обслуживаются без единой правки этого файла.
 *
 *  1. Страница отдаётся тем же сервером, что и данные (туннель напрямую
 *     или localhost) — адрес относительный и верен всегда.
 *
 *  2. Страница лежит на GitHub Pages, а данные за туннелем. Адрес
 *     туннеля приходит ПАРАМЕТРОМ ССЫЛКИ: бот знает его и подставляет
 *     в кнопку сам, потому что перечитывает лог туннеля.
 *
 *     Это главное, ради чего параметр заведён. Имя быстрого туннеля
 *     меняется при каждом запуске, и без параметра адрес пришлось бы
 *     вписывать сюда руками и перезаливать страницу — то есть ломать
 *     приложение в тот день, когда об этом забудут.
 *
 *  3. Страница открыта на Pages без параметра (например, по закладке) —
 *     тогда данных нет и приложение честно об этом скажет. Гадать
 *     бессмысленно: чужой адрес угадать нельзя, а старый, вписанный
 *     когда-то, уже мёртв.
 */
(function () {
  var fromLink = new URLSearchParams(location.search).get('api');
  if (fromLink) {
    // Только https и только туннель Cloudflare: параметр приходит из
    // адресной строки, то есть подставить туда можно что угодно. Без
    // проверки чужая ссылка увела бы подпись Telegram на чужой сервер,
    // а подпись — это доступ к платной части на сутки.
    if (/^https:\/\/[a-z0-9-]+\.trycloudflare\.com\/?$/.test(fromLink)) {
      window.API_BASE = fromLink.replace(/\/$/, '');
      return;
    }
  }
  window.API_BASE = location.hostname.endsWith('github.io') ? null : '';
})();
