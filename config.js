/* Адрес API — единственное, что меняется при переезде.
 *
 * Интерфейс лежит на постоянном https-адресе (GitHub Pages), а данные
 * отдаёт ноутбук с ботом через туннель, и адрес туннеля меняется при
 * каждом его перезапуске. Держать его отдельным файлом — значит менять
 * одну строку вместо поиска по коду; так же это позволяет не пересобирать
 * и не перезаливать приложение целиком ради смены адреса.
 *
 * На localhost адрес подставляется сам, чтобы прототип открывался без
 * правок при разработке. */
window.API_BASE = (location.hostname === 'localhost' || location.hostname === '127.0.0.1')
  ? 'http://localhost:877'
  : 'ЗАМЕНИТЬ_НА_АДРЕС_ТУННЕЛЯ';
