/* Адрес API.
 *
 * Два случая, и оба обслуживаются без правок:
 *
 *  1. Интерфейс раздаётся тем же сервером, что и данные (туннель или
 *     localhost) — адрес относительный, и он верен всегда, как бы ни
 *     менялся туннель. Это основной путь.
 *
 *  2. Интерфейс лежит на GitHub Pages отдельно — тогда нужен полный адрес
 *     туннеля, и меняется он здесь, в одной строке.
 *
 * Относительный путь по умолчанию выбран не из лени: адрес туннеля
 * меняется при каждом его перезапуске, и любая схема, где его надо
 * вписывать, ломается ровно тогда, когда об этом забудут.
 */
